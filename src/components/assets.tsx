import { useRef, useState } from 'react'
import { Download, Eye, FileText, Trash2, UploadCloud } from 'lucide-react'
import type { Asset, AssetType, Product } from '../types'
import { ASSET_LABEL, ASSET_TYPES, marketLabel } from '../data/reference'
import { addAsset, userName, useStore } from '../data/store'
import { assetImageUrl } from '../lib/artwork'
import { downloadAsset } from '../lib/files'
import { formatDate, formatSize } from '../lib/format'
import { Modal } from './ui'

export function AssetCard({ p, a, onPreview, onDelete, showProduct }: { p: Product; a: Asset; onPreview: () => void; onDelete?: () => void; showProduct?: boolean }) {
  const blobUrls = useStore((s) => s.blobUrls)
  const img = assetImageUrl(p, a, blobUrls)
  return (
    <div className="acard">
      <button className="acard-img" onClick={onPreview} aria-label={`Preview ${a.fileName}`}>
        {img ? <img src={img} alt="" loading="lazy" /> : <FileText size={40} />}
        <span className="acard-type">{ASSET_LABEL[a.type]}</span>
      </button>
      <div className="acard-body">
        {showProduct && <span className="small strong clamp-1">{p.name} – {p.species}</span>}
        <span className="acard-name clamp-1" title={a.fileName}>{a.fileName}</span>
        <span className="muted small">{formatSize(a.sizeKb)} · {a.scope === 'global' ? 'Global' : marketLabel(a.scope, true)}</span>
        <span className="muted small clamp-1">{a.source === 'bundled' && a.sourceUrl ? 'Imported from biomar.com' : `${userName(a.uploadedBy)} · ${formatDate(a.uploadedAt)}`}</span>
      </div>
      <div className="acard-actions">
        <button className="icon-btn" onClick={onPreview} aria-label="Preview" title="Preview"><Eye size={16} /></button>
        <button className="icon-btn" onClick={() => downloadAsset(p, a, blobUrls)} aria-label="Download" title="Download"><Download size={16} /></button>
        {onDelete && <button className="icon-btn danger" onClick={onDelete} aria-label="Delete" title="Delete"><Trash2 size={16} /></button>}
      </div>
    </div>
  )
}

export function PreviewModal({ p, a, onClose }: { p: Product; a: Asset; onClose: () => void }) {
  const blobUrls = useStore((s) => s.blobUrls)
  const img = assetImageUrl(p, a, blobUrls)
  const isUploadedPdf = a.source === 'upload' && a.mime === 'application/pdf'
  return (
    <Modal title={a.fileName} onClose={onClose} wide footer={<>
      <span className="muted small grow">
        {ASSET_LABEL[a.type]} · {formatSize(a.sizeKb)} · {a.scope === 'global' ? 'Global' : marketLabel(a.scope)} ·{' '}
        {a.sourceUrl ? <>imported from <a href={a.sourceUrl} target="_blank" rel="noreferrer">biomar.com</a>, {formatDate(a.uploadedAt)}</> : <>uploaded by {userName(a.uploadedBy)}, {formatDate(a.uploadedAt)}</>}
      </span>
      <button className="btn btn-primary" onClick={() => downloadAsset(p, a, blobUrls)}><Download size={16} /> Download</button>
    </>}>
      <div className="preview">
        {isUploadedPdf ? (
          <object data={blobUrls[a.id]} type="application/pdf" className="preview-pdf"><p className="muted">PDF preview is not available in this browser. Use Download.</p></object>
        ) : a.source === 'generated' && (a.type === 'datasheet' || a.type === 'brochure') ? (
          <DocPreview p={p} a={a} />
        ) : img ? (
          <img src={img} alt={a.fileName} />
        ) : (
          <p className="muted pad">No preview for this file type. Use Download.</p>
        )}
      </div>
    </Modal>
  )
}

/** HTML rendition of a generated datasheet – same content as the downloadable PDF. */
function DocPreview({ p, a }: { p: Product; a: Asset }) {
  return (
    <article className="doc">
      <header className="doc-head"><span className="doc-logo">BioMar</span><span>{a.type === 'brochure' ? 'Product brochure' : 'Technical datasheet'}{a.scope !== 'global' ? ` · ${marketLabel(a.scope)}` : ''}</span></header>
      <h2>{p.name} – {p.species}</h2>
      <table className="doc-table"><tbody>
        {[['Product code', p.code], ['Range', p.range], ['Category', p.categories.join(', ')], ['Production stage', p.stages.join(', ')], ['Feed type', p.feedType], ['Pellet sizes', p.pelletSizes.join(', ')], ['Packaging', p.packaging.join(', ')]].map(([k, v]) => (
          <tr key={k}><th>{k}</th><td>{v || '—'}</td></tr>
        ))}
      </tbody></table>
      {p.marketing.description && <><h3>Description</h3>{p.marketing.description.split(/\n\n+/).map((t, i) => <p key={i}>{t}</p>)}</>}
      {p.marketing.keyBenefits.length > 0 && <><h3>Key benefits</h3><ul>{p.marketing.keyBenefits.map((b, i) => <li key={i}>{b}</li>)}</ul></>}
      <p className="muted small">Sample document generated by the prototype. Values are illustrative.</p>
    </article>
  )
}

export function UploadModal({ p, onClose, defaultType = 'hero', defaultScope = 'global', scopes }: { p: Product; onClose: () => void; defaultType?: AssetType; defaultScope?: string; scopes: string[] }) {
  const [files, setFiles] = useState<File[]>([])
  const [type, setType] = useState<AssetType>(defaultType)
  const [scope, setScope] = useState(defaultScope)
  const [over, setOver] = useState(false)
  const [busy, setBusy] = useState(false)
  const input = useRef<HTMLInputElement>(null)
  const upload = async () => {
    setBusy(true)
    for (const f of files) await addAsset(p.id, f, type, scope)
    setBusy(false)
    onClose()
  }
  return (
    <Modal title={`Upload assets – ${p.name} ${p.species}`} onClose={onClose} footer={<>
      <button className="btn btn-secondary" onClick={onClose}>Cancel</button>
      <button className="btn btn-primary" disabled={!files.length || busy} onClick={upload}>{busy ? 'Uploading…' : `Upload ${files.length || ''} file${files.length === 1 ? '' : 's'}`}</button>
    </>}>
      <div
        className={`drop${over ? ' over' : ''}`}
        onDragOver={(e) => { e.preventDefault(); setOver(true) }}
        onDragLeave={() => setOver(false)}
        onDrop={(e) => { e.preventDefault(); setOver(false); setFiles([...files, ...Array.from(e.dataTransfer.files)]) }}
        onClick={() => input.current?.click()}
        role="button" tabIndex={0} onKeyDown={(e) => e.key === 'Enter' && input.current?.click()}
      >
        <UploadCloud size={32} />
        <strong>Drop files here or click to browse</strong>
        <span className="muted small">Images (JPG, PNG, SVG, WebP) and PDFs</span>
        <input ref={input} type="file" multiple hidden accept="image/*,application/pdf" onChange={(e) => setFiles([...files, ...Array.from(e.target.files ?? [])])} />
      </div>
      {files.length > 0 && (
        <ul className="file-list">
          {files.map((f, i) => <li key={i}><FileText size={14} /> {f.name} <span className="muted small">{formatSize(Math.max(1, Math.round(f.size / 1024)))}</span></li>)}
        </ul>
      )}
      <div className="form-grid">
        <label className="field"><span>Asset type</span>
          <select value={type} onChange={(e) => setType(e.target.value as AssetType)}>{ASSET_TYPES.map((t) => <option key={t.id} value={t.id}>{t.label}{t.required ? ' (required)' : ''}</option>)}</select>
        </label>
        <label className="field"><span>Applies to</span>
          <select value={scope} onChange={(e) => setScope(e.target.value)}>{scopes.map((s) => <option key={s} value={s}>{s === 'global' ? 'Global (all markets)' : marketLabel(s)}</option>)}</select>
        </label>
      </div>
      <p className="muted small">Files are stored in this browser for the prototype.</p>
    </Modal>
  )
}
