// Downloading assets: uploaded files come from IndexedDB, sample assets are generated on the fly
// (SVG artwork rasterised to JPEG/PNG, documents generated as simple PDFs).
import type { Asset, Product } from '../types'
import { ASSET_LABEL, LIFECYCLE_LABEL, marketLabel } from '../data/reference'
import { bagSvg, heroSvg, highresSvg } from './artwork'
import { bundledUrl } from './bundled'

function save(blob: Blob, name: string) {
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = name
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 2000)
}

function rasterise(svg: string, mime: string): Promise<Blob> {
  return new Promise((resolve, reject) => {
    const img = new Image()
    img.onload = () => {
      const canvas = document.createElement('canvas')
      canvas.width = img.naturalWidth || 1200
      canvas.height = img.naturalHeight || 800
      canvas.getContext('2d')!.drawImage(img, 0, 0)
      canvas.toBlob((b) => (b ? resolve(b) : reject(new Error('render failed'))), mime, 0.92)
    }
    img.onerror = reject
    img.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg)
  })
}

export async function downloadAsset(p: Product, a: Asset, blobUrls: Record<string, string>) {
  if (a.source === 'upload') {
    const url = blobUrls[a.id]
    if (!url) return
    const blob = await fetch(url).then((r) => r.blob())
    return save(blob, a.fileName)
  }
  if (a.source === 'bundled') {
    const url = bundledUrl(a)
    if (!url) return
    return save(await fetch(url).then((r) => r.blob()), a.fileName)
  }
  if (a.type === 'hero' || a.type === 'highres' || a.type === 'bag') {
    const svg = a.type === 'hero' ? heroSvg(p) : a.type === 'bag' ? bagSvg(p) : highresSvg(p)
    return save(await rasterise(svg, a.mime === 'image/png' ? 'image/png' : 'image/jpeg'), a.fileName)
  }
  save(datasheetPdf(p, a), a.fileName)
}

/* ---------- Tiny PDF writer (single page, Helvetica) ---------- */

const latin = (s: string) =>
  s.replace(/[–—]/g, '-').replace(/[“”]/g, '"').replace(/[‘’]/g, "'").replace(/…/g, '...').replace(/®/g, '(R)')
    .replace(/[^\x20-\x7e\xa0-\xff]/g, '?').replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)')

function wrap(text: string, max: number): string[] {
  const out: string[] = []
  for (const para of text.split('\n')) {
    let line = ''
    for (const w of para.split(' ')) {
      if ((line + ' ' + w).trim().length > max) { out.push(line); line = w } else line = (line + ' ' + w).trim()
    }
    out.push(line)
  }
  return out
}

export function datasheetPdf(p: Product, a: Asset): Blob {
  const rows: [string, number, boolean][] = [] // text, size, bold
  const add = (t: string, size = 10, bold = false) => rows.push([t, size, bold])
  add(`${p.name} - ${p.species}`, 20, true)
  add(`${a.type === 'brochure' ? 'Product brochure' : ASSET_LABEL[a.type]}${a.scope !== 'global' ? ' - ' + marketLabel(a.scope) : ''}`, 12)
  add('')
  const facts: [string, string][] = [
    ['Product code', p.code], ['Range', p.range], ['Category', p.category], ['Species', p.species],
    ['Production stage', p.stages.join(', ')], ['Feed type', p.feedType], ['Pellet sizes', p.pelletSizes.join(', ')],
    ['Packaging', p.packaging.join(', ')], ['Lifecycle', LIFECYCLE_LABEL[p.lifecycle]],
  ]
  for (const [k, v] of facts) add(`${k}:  ${v || '-'}`, 10)
  add('')
  if (p.marketing.description) {
    add('Description', 12, true)
    wrap(p.marketing.description, 95).forEach((l) => add(l))
    add('')
  }
  if (p.marketing.keyBenefits.length) {
    add('Key benefits', 12, true)
    p.marketing.keyBenefits.forEach((b) => wrap('- ' + b, 92).forEach((l, i) => add(i ? '  ' + l : l)))
  }
  add('')
  add('Sample document generated by the BioMar PIM prototype. Values are illustrative.', 8)

  let y = 790
  let content = 'BT\n'
  for (const [t, size, bold] of rows) {
    y -= size + 6
    if (y < 40) break
    content += `/${bold ? 'F2' : 'F1'} ${size} Tf 1 0 0 1 50 ${y} Tm (${latin(t)}) Tj\n`
  }
  content += 'ET\n0.06 0.13 0.28 rg 0 812 595 30 re f\n'
  const objs = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>',
    `<< /Length ${content.length} >>\nstream\n${content}endstream`,
  ]
  let pdf = '%PDF-1.4\n'
  const offsets: number[] = []
  objs.forEach((o, i) => { offsets.push(pdf.length); pdf += `${i + 1} 0 obj\n${o}\nendobj\n` })
  const xref = pdf.length
  pdf += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n` + offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('')
  pdf += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`
  const bytes = new Uint8Array(pdf.length)
  for (let i = 0; i < pdf.length; i++) bytes[i] = pdf.charCodeAt(i) & 0xff
  return new Blob([bytes], { type: 'application/pdf' })
}
